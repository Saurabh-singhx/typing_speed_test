export const LANGUAGE_MAP = new Map<LanguageCode, LanguageInfo>(
  SUPPORTED_LANGUAGES.map((lang) => [lang.code, lang])
);

export function getLanguageInfo(code: LanguageCode | string): LanguageInfo {
  return LANGUAGE_MAP.get(code as LanguageCode) || SUPPORTED_LANGUAGES[0];
}

export function isValidLanguage(code: string): code is LanguageCode {
  return LANGUAGE_MAP.has(code as LanguageCode);
}
